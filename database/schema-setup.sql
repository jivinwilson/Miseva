CREATE SCHEMA IF NOT EXISTS miseva AUTHORIZATION misva_owner;
REVOKE ALL ON SCHEMA miseva FROM PUBLIC;
GRANT USAGE ON SCHEMA miseva TO misva_app;
ALTER DEFAULT PRIVILEGES FOR ROLE misva_owner IN SCHEMA miseva GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO misva_app;
ALTER DEFAULT PRIVILEGES FOR ROLE misva_owner IN SCHEMA miseva GRANT USAGE, SELECT ON SEQUENCES TO misva_app;
ALTER DEFAULT PRIVILEGES FOR ROLE misva_owner IN SCHEMA miseva GRANT EXECUTE ON FUNCTIONS TO misva_app;
